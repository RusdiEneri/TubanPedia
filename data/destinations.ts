function assertDestinationData(records: Destination[]) {
  const ids = new Set(records.map(({ id }) => id));
  const slugs = new Set(records.map(({ slug }) => slug));
  const complete = records.every(
    (item) =>
      item.name &&
      item.category &&
      item.description &&
      Number.isFinite(item.latitude) &&
      Number.isFinite(item.longitude) &&
      item.openingHours &&
      item.ticketPrice &&
      item.coverImage &&
      item.gallery.length >= 2 &&
      item.gallery.every(Boolean)
  );
  if (records.length !== 15 || ids.size !== records.length || slugs.size !== records.length || !complete) {
    throw new Error("Destination seed data failed integrity validation.");
  }
}

